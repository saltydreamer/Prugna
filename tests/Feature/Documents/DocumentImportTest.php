    use RefreshDatabase;

    private User $admin;

    protected function setUp(): void
    {
        parent::setUp();

        Storage::fake('local');
        $this->admin = User::factory()->admin()->create();

        app(Settings::class)->set([
            'company.name' => 'Officina Digitale Srl',
            'company.vat_number' => '01234567897',
            'company.address' => 'Via Roma 1',
            'company.postal_code' => '20121',
            'company.city' => 'Milano',
            'company.province' => 'MI',
        ]);
    }

    /**
     * An e-invoice as a supplier would send it: generated by our own FatturaPA exporter.
     */
    private function receivedInvoiceXml(): string
    {
        $customer = Organization::factory()->withDetails(1, 0)->create();
        $invoice = app(SaveInvoice::class)->handle(new Invoice, [
            'organization_id' => $customer->id,
            'issue_date' => today()->toDateString(),
            'payment_term_id' => PaymentTerm::default()->id,
            'lines' => [['type' => 'item', 'description' => 'Manutenzione server', 'quantity' => 2, 'unit_price' => 150, 'vat_rate_id' => VatRate::default()->id]],
        ]);

        return app(FatturaPaXml::class)->make(app(IssueInvoice::class)->handle($invoice));
    }

    private function enableAi(): void
    {
        app(Settings::class)->set(['ai.enabled' => true, 'ai.api_key' => 'sk-or-test', 'ai.model' => 'anthropic/claude-test', 'ai.privacy' => 'no_training']);
    }

    /**
     * @param  array<string, mixed>  ...$results  One per expected reading, in order.
     */
    private function fakeOpenRouter(array ...$results): void
    {
        $sequence = Http::sequence();

        foreach ($results as $data) {
            $sequence->push([
                'model' => 'anthropic/claude-test',
                'choices' => [['message' => ['role' => 'assistant', 'content' => json_encode($data)]]],
                'usage' => ['prompt_tokens' => 1800, 'completion_tokens' => 400, 'cost' => 0.0123],
            ]);
        }

        Http::fake([
            'openrouter.ai/api/v1/models*' => Http::response(['data' => [[
                'id' => 'anthropic/claude-test', 'name' => 'Claude test', 'context_length' => 200000,
                'architecture' => ['input_modalities' => ['text', 'image', 'file']],
                'supported_parameters' => ['response_format', 'structured_outputs'],
                'pricing' => ['prompt' => '0.000004', 'completion' => '0.00002'],
            ]]]),
            'openrouter.ai/api/v1/chat/completions' => $sequence,
        ]);
    }

    public function test_a_received_e_invoice_is_imported_without_ai(): void
    {
        Http::fake();
        $xml = $this->receivedInvoiceXml();
        // The issuer (our company data in the XML) is already a supplier.
        $supplier = Organization::factory()->supplier()->create(['vat_number' => '01234567897']);

        $response = $this->actingAs($this->admin)->post('/documents/read', [
            'kind' => 'expense',
            'file' => UploadedFile::fake()->createWithContent('IT01234567897_00001.xml', $xml),
        ]);

        $extraction = AiExtraction::sole();
        $response->assertRedirect("/purchases/expenses/create?extraction={$extraction->id}");
        $this->assertSame('xml', $extraction->source);
        Http::assertNothingSent();

        $this->actingAs($this->admin)->get("/purchases/expenses/create?extraction={$extraction->id}")
            ->assertInertia(fn (Assert $page) => $page
                ->component('purchases/expenses/Edit')
                ->where('defaults.supplier_id', $supplier->id)
                ->where('defaults.type', 'invoice')
                ->where('defaults.number', 'FT-'.today()->year.'-0001')
                ->where('defaults.due_date', today()->addDays(30)->toDateString())
                ->where('defaults.payment_method', 'bank_transfer')
                ->where('defaults.lines.0.description', 'Manutenzione server')
                ->where('defaults.lines.0.unit_price', 150)
                ->where('defaults.lines.0.vat_rate_id', VatRate::default()->id)
                ->where('review.document_total', 366)
                ->where('review.warnings', []));

        // Saving the draft attaches the original file.
        $this->actingAs($this->admin)->post('/purchases/expenses', [
            'type' => 'invoice',
            'supplier_id' => $supplier->id,
            'number' => 'FT-'.today()->year.'-0001',
            'document_date' => today()->toDateString(),
            'ai_extraction_id' => $extraction->id,
            'lines' => [['type' => 'item', 'description' => 'Manutenzione server', 'quantity' => 2, 'unit_price' => 150, 'vat_rate_id' => VatRate::default()->id]],
        ])->assertRedirect();

        $this->assertSame($extraction->file_path, Expense::sole()->attachment_path);
        $this->assertSame('xml', Expense::sole()->source);

        // Reading the same document again warns that it's already recorded.
        $this->actingAs($this->admin)->post('/documents/read', [
            'kind' => 'expense',
            'file' => UploadedFile::fake()->createWithContent('copia.xml', $xml),
        ]);

        $this->actingAs($this->admin)->get('/purchases/expenses/create?extraction='.AiExtraction::latest('id')->value('id'))
            ->assertInertia(fn (Assert $page) => $page->where('review.duplicate.id', Expense::sole()->id));
    }

    public function test_signed_p7m_invoices_are_unwrapped(): void
    {
        $xml = $this->receivedInvoiceXml();
        $p7m = "\x30\x82\x1a\x2b\x06\x09signed-envelope".$xml."\x00\xa0\x82trailer-signature";

        $this->actingAs($this->admin)->post('/documents/read', [
            'kind' => 'expense',
            'file' => UploadedFile::fake()->createWithContent('IT01234567897_00001.xml.p7m', $p7m),
        ])->assertRedirect();

        $this->assertSame('Officina Digitale Srl', AiExtraction::sole()->result['supplier']['name']);
    }

    public function test_a_receipt_photo_is_read_by_the_ai(): void
    {
        $this->enableAi();
        $supplier = Organization::factory()->supplier()->create(['vat_number' => '00743110157']);
        $this->fakeOpenRouter([
            'document_type' => 'receipt',
            'supplier' => ['name' => 'Bar Centrale', 'vat_number' => 'IT00743110157', 'tax_code' => null, 'address' => null, 'postal_code' => null, 'city' => null, 'province' => null, 'country' => 'IT', 'email' => null, 'pec' => null, 'phone' => null],
            'number' => '0042',
            'date' => '2026-10-30',
            'due_date' => null,
            'payment_method' => 'card',
            'description' => 'Pranzo di lavoro',
            'lines' => [['description' => 'Pranzo', 'quantity' => 2, 'unit_price' => 13.64, 'vat_rate' => 10, 'total' => 27.27]],
            'total_taxable' => 27.27,
            'total_vat' => 2.73,
            'total' => 30.00,
            'warnings' => [],
        ]);

        $this->actingAs($this->admin)->post('/documents/read', [
            'kind' => 'expense',
            'file' => UploadedFile::fake()->image('scontrino.jpg', 3000, 4000),
        ])->assertRedirect();

        $extraction = AiExtraction::sole();
        $this->assertSame('ai', $extraction->source);
        $this->assertSame('0.012300', $extraction->cost);

        Http::assertSent(function (Request $request): bool {
            if (! str_ends_with($request->url(), '/chat/completions')) {
                return false;
            }

            $image = $request['messages'][1]['content'][0];

            return $request->hasHeader('Authorization', 'Bearer sk-or-test')
                && $request['model'] === 'anthropic/claude-test'
                && $request['response_format']['type'] === 'json_schema'
                && $request['response_format']['json_schema']['strict'] === true
                && $request['provider']['data_collection'] === 'deny'
                && $request['provider']['require_parameters'] === true
                && $image['type'] === 'image_url'
                && str_starts_with($image['image_url']['url'], 'data:image/jpeg;base64,')
                // Photos are shrunk before being sent.
                && strlen($image['image_url']['url']) < 2_000_000;
        });

        $this->actingAs($this->admin)->get("/purchases/expenses/create?extraction={$extraction->id}")
            ->assertInertia(fn (Assert $page) => $page
                ->where('defaults.supplier_id', $supplier->id)
                ->where('defaults.type', 'receipt')
                ->where('defaults.document_date', '2026-10-30')
                // Paid on the spot.
                ->where('defaults.paid_at', '2026-10-30')
                ->where('defaults.lines.0.vat_rate_id', VatRate::query()->where('rate', 10)->whereNull('nature')->value('id'))
                ->where('review.model', 'anthropic/claude-test'));
    }

    public function test_unknown_suppliers_are_suggested_and_customers_are_never_used(): void
    {
        $this->enableAi();
        $customer = Organization::factory()->create(['vat_number' => '00743110157']);
        $result = fn (string $vat) => [
            'document_type' => 'invoice',
            'supplier' => ['name' => 'Ferramenta Bianchi', 'vat_number' => $vat, 'tax_code' => null, 'address' => 'Via Po 3', 'postal_code' => '10121', 'city' => 'Torino', 'province' => 'to', 'country' => 'IT', 'email' => null, 'pec' => null, 'phone' => null],
            'number' => '7', 'date' => '2026-10-01', 'due_date' => '2026-10-31', 'payment_method' => 'bank_transfer', 'description' => null,
            'lines' => [['description' => 'Viti', 'quantity' => 1, 'unit_price' => 100, 'vat_rate' => 22, 'total' => 100]],
            'total_taxable' => 100, 'total_vat' => 22, 'total' => 130, 'warnings' => [],
        ];

        $this->fakeOpenRouter($result('01234567897'), $result('00743110157'));
        $this->actingAs($this->admin)->post('/documents/read', ['kind' => 'expense', 'file' => UploadedFile::fake()->image('fattura.png')]);

        $this->actingAs($this->admin)->get('/purchases/expenses/create?extraction='.AiExtraction::latest('id')->value('id'))
            ->assertInertia(fn (Assert $page) => $page
                ->where('defaults.supplier_id', null)
                ->where('review.supplier_suggestion.name', 'Ferramenta Bianchi')
                ->where('review.supplier_suggestion.location.province', 'TO')
                // 100 + 22% is 122, the document says 130.
                ->where('review.warnings', fn ($warnings) => count($warnings) === 1));

        $this->actingAs($this->admin)->post('/documents/read', ['kind' => 'expense', 'file' => UploadedFile::fake()->image('fattura2.png')]);

        $this->actingAs($this->admin)->get('/purchases/expenses/create?extraction='.AiExtraction::latest('id')->value('id'))
            ->assertInertia(fn (Assert $page) => $page
                ->where('defaults.supplier_id', null)
                ->where('review.supplier_suggestion', null)
                ->where('review.warnings.0', fn (string $warning) => str_contains($warning, $customer->name)));
    }

    public function test_a_business_card_prefills_a_new_supplier(): void
    {
        $this->enableAi();
        $this->fakeOpenRouter([
            'name' => 'Elettroforniture Nord Srl', 'type' => 'company', 'vat_number' => '01234567897', 'tax_code' => null, 'sdi_code' => 'abc1234',
            'pec' => null, 'email' => 'info@elettronord.example', 'phone' => '+39 02 1234567', 'website' => 'elettronord.example',
            'address' => 'Via Torino 5', 'postal_code' => '20100', 'city' => 'Milano', 'province' => 'MI', 'country' => 'IT',
            'contact' => ['first_name' => 'Laura', 'last_name' => 'Verdi', 'job_title' => 'Commerciale', 'email' => 'laura@elettronord.example', 'phone' => null],
            'warnings' => [],
        ]);

        $this->actingAs($this->admin)->post('/documents/read', ['kind' => 'supplier', 'file' => UploadedFile::fake()->image('biglietto.jpg')])
            ->assertRedirect('/registry/suppliers/create?extraction='.AiExtraction::sole()->id);

        $this->actingAs($this->admin)->get('/registry/suppliers/create?extraction='.AiExtraction::sole()->id)
            ->assertInertia(fn (Assert $page) => $page
                ->component('registry/organizations/Create')
                ->where('role.value', 'supplier')
                ->where('defaults.name', 'Elettroforniture Nord Srl')
                ->where('defaults.sdi_code', 'ABC1234')
                ->where('defaults.location.city', 'Milano')
                ->where('defaults.contact.last_name', 'Verdi'));

        // Saving creates the supplier with its office and contact.
        $this->actingAs($this->admin)->post('/registry/organizations', [
            'role' => 'supplier', 'name' => 'Elettroforniture Nord Srl', 'type' => 'company', 'vat_number' => '01234567897',
            'location' => ['address' => 'Via Torino 5', 'postal_code' => '20100', 'city' => 'Milano', 'province' => 'MI', 'country' => 'IT'],
            'contact' => ['first_name' => 'Laura', 'last_name' => 'Verdi', 'job_title' => 'Commerciale', 'email' => 'laura@elettronord.example'],
        ])->assertRedirect();

        $supplier = Organization::query()->where('name', 'Elettroforniture Nord Srl')->sole();
        $this->assertTrue($supplier->isSupplier());
        $this->assertSame('Milano', $supplier->locations()->first()->city);
        $this->assertSame('Verdi', $supplier->contacts()->first()->last_name);
    }

    public function test_errors_are_reported_and_logged(): void
    {
        // Not configured.
        $this->actingAs($this->admin)->post('/documents/read', ['kind' => 'expense', 'file' => UploadedFile::fake()->image('a.jpg')])
            ->assertSessionHasErrors('file');
        $this->assertSame('failed', AiExtraction::sole()->status);

        $this->enableAi();
        Http::fake(['openrouter.ai/*' => Http::response(['error' => ['message' => 'Insufficient credits']], 402)]);

        $this->actingAs($this->admin)->post('/documents/read', ['kind' => 'expense', 'file' => UploadedFile::fake()->image('b.jpg')])
            ->assertSessionHasErrors(['file' => 'Credito OpenRouter esaurito: ricaricalo su openrouter.ai.']);
    }

    public function test_reading_with_ai_needs_its_permission(): void
    {
        $this->enableAi();
        Http::fake();
        $user = User::factory()->withRole(Role::User)->create();
        $user->givePermissionTo('expenses.manage', 'expenses.view');

        $this->actingAs($user)->post('/documents/read', ['kind' => 'expense', 'file' => UploadedFile::fake()->image('a.jpg')])->assertForbidden();

        // E-invoices are read without AI.
        $this->actingAs($user)->post('/documents/read', [
            'kind' => 'expense',
            'file' => UploadedFile::fake()->createWithContent('fattura.xml', $this->receivedInvoiceXml()),
        ])->assertRedirect();
        Http::assertNothingSent();
    }
}
